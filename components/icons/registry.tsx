export function getIcon(key: string): LucideIcon {
  return ICONS[key]?.Icon ?? HelpCircle;
}

export function iconLabel(key: string, locale: Locale = "en"): string {
  return ICONS[key]
    ? translate(locale, ICONS[key].labelKey as "icons.person")
    : translate(locale, "ui.icon");
}

export interface IconOption {
  key: string;
  label: string;
  Icon: LucideIcon;
}

export function iconOptions(
  keys: readonly string[],
  locale: Locale = "en",
): IconOption[] {
  return keys.map((key) => ({
    key,
    label: iconLabel(key, locale),
    Icon: getIcon(key),
  }));
}

/** Render a stored icon key. Decorative by default (aria-hidden). */
export function IconByName({
  name,
  size = 24,
  className,
}: {
  name: string;
  size?: number;
  className?: string;
}) {
  return createElement(getIcon(name), {
    size,
    className,
    "aria-hidden": true,
  });
}
